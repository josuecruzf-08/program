// Declaramos el radio del círculo
let radio = 5;
let pi = 3.14159;

// Calculamos el perímetro
let perimetro = 2 * pi * radio;

// Calculamos el área
let area = pi * radio ** 2;

// Mostramos los resultados en consola
console.log(` Radio: ${radio} \n perimetro: ${perimetro.toFixed(2)} \n Area: ${area.toFixed(2)}`);